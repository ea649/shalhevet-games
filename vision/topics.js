// תמצית קצרה של התשובה — לשלט שהילדים מחזיקים כשאין נושא מוכר
const STOP = new Set('אני את אתה הוא היא אנחנו הם הן של על עם כל כך גם רק עוד יותר מאוד מאד כמו אבל או אם כי זה זו זאת אלה יהיה יהיו תהיה היה הייתה להיות שיהיה שיהיו יש אין לא כן את בית הספר ביה"ס ביהס בבית בסוף שנה השנה אחרי לאחר יישום התחום שלי שלנו שלהם רואה רואים אראה נראה אני רואה ספר הספר ביהס שכולו כולו כולם כולן שבו בו ילדים הילדים תלמידים התלמידים תלמידות התלמידות שלהבות חבד'.split(' ').map(w => normalize(w).trim()));
export function gist(text, max = 4) {
  const words = String(text || '').replace(/[.,!?;:"״()\-–]/g, ' ').split(/\s+/).filter(Boolean);
  if (words.join(' ').length <= 26) return words.join(' ');
  const keep = words.filter(w => !STOP.has(normalize(w).trim()) && w.length > 1);
  return (keep.length ? keep : words).slice(0, max).join(' ');
}
