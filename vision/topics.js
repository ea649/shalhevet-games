const FINALS = { 'ך': 'כ', 'ם': 'מ', 'ן': 'נ', 'ף': 'פ', 'ץ': 'צ' };
export function normalize(s) {
  return ' ' + String(s || '').toLowerCase()
    .replace(/[֑-ׇ]/g, '')            // ניקוד וטעמים
    .replace(/["'״׳`]/g, '')
    .replace(/[ךםןףץ]/g, c => FINALS[c])
    .replace(/[^א-תa-z0-9 \-]+/g, ' ')
    .replace(/\s+/g, ' ') + ' ';
}

function hits(text, kw) {
  if (kw.startsWith('=')) {
    const w = normalize(kw.slice(1)).trim();
    return new RegExp(`(^|\\s)[והבלכמשד]{0,3}${w}(?=\\s)`).test(text);
  }
  return text.includes(normalize(kw).trim());
}

// מחזיר [ראשי, משני?] — התשובה קובעת, והתחום של המנהלת נותן משקל קטן כשובר שוויון
const GENERIC = /(?<=\s)[והבלמש]{0,3}(בית ה?ספר|בתי ה?ספר|ביהס|שלהבות|חבד)(?=\s)|(לקחת|לוקחימ|לוקחת|לוקח|נלקח) בחשבונ/g;
export function classify(answer, domain = '') {
  const a = normalize(answer).replace(GENERIC, ' '), d = normalize(domain);
  const dom = domainOf(domain);
  const scores = TOPICS.filter(t => t.id !== 'vision' && t.id !== 'custom').map(t => {
    let own = 0, s = 0; // own = רק מהתשובה עצמה
    for (const k of t.strong) { if (hits(a, k)) own += 2; if (hits(d, k)) s += 0.6; }
    for (const k of t.weak) { if (hits(a, k)) own += 1; if (hits(d, k)) s += 0.3; }
    if (dom && dom.topic === t.id) s += 0.8;
    return { id: t.id, s: own ? own + s : 0, own };
  }).filter(x => x.s > 0).sort((x, y) => y.s - x.s);
  // אין בתשובה עצמה שום נושא מוכר → מייצרים לה איור משלה (התחום לבד לא מספיק)
  if (!scores.length || scores[0].own < 0.9) return ['vision'];
  const out = [scores[0].id];
  if (scores[1] && scores[1].s >= 1) out.push(scores[1].id);
  return out;
}

